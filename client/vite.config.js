import { defineConfig, loadEnv } from "vite";
import react from "@vitejs/plugin-react";

/**
 * Returns the origin of a URL, or null when it's empty/invalid.
 *
 * @param {string | undefined} url
 * @returns {string | null}
 */
function originOf(url) {
  try {
    return url ? new URL(url).origin : null;
  } catch {
    return null;
  }
}

/**
 * Emits Netlify `_headers` with a strict Content-Security-Policy built from the
 * same env vars the app is compiled with, so the API origin and Firebase auth
 * domain are always allowed — and nothing else.
 *
 * Set VITE_CSP_REPORT_ONLY=true to ship the policy in report-only mode while
 * validating a new deployment.
 *
 * @param {Record<string, string>} env
 * @returns {import("vite").Plugin}
 */
function securityHeaders(env) {
  const api = originOf(env.VITE_API_URL);
  const authDomain = env.VITE_FIREBASE_AUTH_DOMAIN ? `https://${env.VITE_FIREBASE_AUTH_DOMAIN}` : null;

  const csp = [
    "default-src 'self'",
    // Firebase Auth's popup flow loads gapi from apis.google.com.
    "script-src 'self' https://apis.google.com",
    "style-src 'self'",
    "img-src 'self' data: https://*.googleusercontent.com",
    "font-src 'self'",
    [
      "connect-src 'self'",
      api,
      "https://identitytoolkit.googleapis.com",
      "https://securetoken.googleapis.com",
      "https://www.googleapis.com",
    ]
      .filter(Boolean)
      .join(" "),
    ["frame-src", authDomain, "https://accounts.google.com"].filter(Boolean).join(" "),
    "manifest-src 'self'",
    "worker-src 'none'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "upgrade-insecure-requests",
  ].join("; ");

  const cspHeader =
    env.VITE_CSP_REPORT_ONLY === "true" ? "Content-Security-Policy-Report-Only" : "Content-Security-Policy";

  const headers = `# Generated by vite.config.js at build time — do not edit by hand.
/*
  ${cspHeader}: ${csp}
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()
  Strict-Transport-Security: max-age=63072000; includeSubDomains
  Cross-Origin-Opener-Policy: same-origin-allow-popups
  Cross-Origin-Resource-Policy: same-origin

/assets/*
  Cache-Control: public, max-age=31536000, immutable

/index.html
  Cache-Control: no-cache
`;

  return {
    name: "security-headers",
    apply: "build",
    generateBundle() {
      this.emitFile({ type: "asset", fileName: "_headers", source: headers });
    },
  };
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), "VITE_");
  return {
    plugins: [react(), securityHeaders(env)],
    server: {
      port: 3001, // matches the localhost origin in the server's ALLOWED_ORIGINS
      proxy: {
        // Used when VITE_API_URL is empty: /api → local backend.
        "/api": { target: "http://localhost:3000", changeOrigin: true },
      },
    },
    build: {
      target: "es2022",
      sourcemap: false,
      modulePreload: { polyfill: false },
      rolldownOptions: {
        output: {
          // Firebase changes rarely; a separate chunk stays cached across deploys.
          codeSplitting: {
            groups: [{ name: "firebase", test: /[\\/]node_modules[\\/](@firebase|firebase)[\\/]/ }],
          },
        },
      },
    },
  };
});
